export function stateNameToCode(name: string): string | undefined {
  const target = name.trim().toLowerCase()
  return INDIAN_STATES.find((s) => s.name.toLowerCase() === target)?.code
}

export function stateCodeToName(code: string): string | undefined {
  return INDIAN_STATES.find((s) => s.code === code)?.name
}

// Structural GSTIN check (first two digits must be a valid state code).
// Full checksum validation happens on the server (internal/tax).
export function isValidGSTINShape(gstin: string): boolean {
  if (!/^[0-9]{2}[A-Z]{5}[0-9]{4}[A-Z][1-9A-Z]Z[0-9A-Z]$/.test(gstin)) return false
  return stateCodeToName(gstin.slice(0, 2)) !== undefined
}